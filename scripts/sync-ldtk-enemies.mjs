import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();

const sourcePath = path.join(
  root,
  "assets/levels/impressario-world.ldtk"
);

const outputPath = path.join(
  root,
  "src/world/WorldEnemies.ts"
);

const checkOnly =
  process.argv.includes("--check");

const expectedCounts = {
  Stagehand: 3,
  CardThrower: 2,
  ShadowAcrobat: 2,
  LightWraith: 2,
  CardSentry: 3,
  RoyalEcho: 4,
  MirrorCore: 4
};

const project = JSON.parse(
  fs.readFileSync(sourcePath, "utf8")
);

if (project.jsonVersion !== "1.5.3") {
  throw new Error(
    `Expected LDtk JSON 1.5.3, got ${
      String(project.jsonVersion)
    }.`
  );
}

const level = project.levels?.find(
  candidate =>
    candidate.identifier ===
    "ImpressarioWorld"
);

if (!level) {
  throw new Error(
    "LDtk level ImpressarioWorld is missing."
  );
}

const layer = level.layerInstances?.find(
  candidate =>
    candidate.__identifier === "Entities"
);

if (!layer) {
  throw new Error(
    "LDtk Entities layer is missing."
  );
}

const fieldValue = (
  entity,
  identifier
) => {
  const field =
    entity.fieldInstances?.find(
      candidate =>
        candidate.__identifier === identifier
    );

  if (!field) {
    throw new Error(
      `EnemySpawn is missing ${identifier}.`
    );
  }

  return field.__value;
};

const spawns = layer.entityInstances
  .filter(
    entity =>
      entity.__identifier === "EnemySpawn"
  )
  .map(entity => ({
    id: String(
      fieldValue(entity, "Identifier")
    ),
    group: String(
      fieldValue(entity, "Group")
    ),
    kind: String(
      fieldValue(entity, "Kind")
    ),
    x: Number(entity.px?.[0]),
    y: Number(entity.px?.[1]),
    patrolLeft: Number(
      fieldValue(entity, "PatrolLeft")
    ),
    patrolRight: Number(
      fieldValue(entity, "PatrolRight")
    ),
    phase: Number(
      fieldValue(entity, "Phase")
    )
  }))
  .sort(
    (left, right) =>
      left.x - right.x ||
      left.y - right.y ||
      left.id.localeCompare(right.id)
  );

if (spawns.length !== 20) {
  throw new Error(
    `Expected 20 enemy spawns, got ${spawns.length}.`
  );
}

const identifiers = new Set();

for (const spawn of spawns) {
  if (!spawn.id) {
    throw new Error(
      "EnemySpawn Identifier must not be empty."
    );
  }

  if (identifiers.has(spawn.id)) {
    throw new Error(
      `Duplicate EnemySpawn Identifier: ${spawn.id}`
    );
  }

  identifiers.add(spawn.id);

  if (!(spawn.group in expectedCounts)) {
    throw new Error(
      `Unknown enemy group ${spawn.group}.`
    );
  }

  for (
    const [name, value] of
    Object.entries({
      x: spawn.x,
      y: spawn.y,
      patrolLeft: spawn.patrolLeft,
      patrolRight: spawn.patrolRight,
      phase: spawn.phase
    })
  ) {
    if (!Number.isFinite(value)) {
      throw new Error(
        `${spawn.id} has invalid ${name}.`
      );
    }
  }

  if (
    spawn.patrolLeft > spawn.x ||
    spawn.patrolRight < spawn.x
  ) {
    throw new Error(
      `${spawn.id} lies outside its patrol bounds.`
    );
  }
}

for (
  const [group, expected] of
  Object.entries(expectedCounts)
) {
  const actual = spawns.filter(
    spawn =>
      spawn.group === group
  ).length;

  if (actual !== expected) {
    throw new Error(
      `Expected ${expected} ${group} spawns, got ${actual}.`
    );
  }
}

const groupNames =
  Object.keys(expectedCounts);

const lines = [
  "/* Generated by scripts/sync-ldtk-enemies.mjs. */",
  "/* Edit assets/levels/impressario-world.ldtk, not this file. */",
  "",
  "export type WorldEnemyGroup =",
  ...groupNames.map(
    (group, index) =>
      `  | ${JSON.stringify(group)}${
        index === groupNames.length - 1
          ? ";"
          : ""
      }`
  ),
  "",
  "export type WorldEnemyKind =",
  '  | ""',
  '  | "duelist"',
  '  | "caster"',
  '  | "mime";',
  "",
  "export interface WorldEnemySpawn {",
  "  readonly id: string;",
  "  readonly group: WorldEnemyGroup;",
  "  readonly kind: WorldEnemyKind;",
  "  readonly x: number;",
  "  readonly y: number;",
  "  readonly patrolLeft: number;",
  "  readonly patrolRight: number;",
  "  readonly phase: number;",
  "}",
  "",
  "export const WORLD_ENEMY_SPAWNS = ["
];

for (const spawn of spawns) {
  lines.push(
    "  {",
    `    id: ${JSON.stringify(spawn.id)},`,
    `    group: ${JSON.stringify(spawn.group)},`,
    `    kind: ${JSON.stringify(spawn.kind)},`,
    `    x: ${spawn.x},`,
    `    y: ${spawn.y},`,
    `    patrolLeft: ${spawn.patrolLeft},`,
    `    patrolRight: ${spawn.patrolRight},`,
    `    phase: ${spawn.phase}`,
    "  },"
  );
}

lines.push(
  "] as const satisfies readonly WorldEnemySpawn[];",
  "",
  "export function getWorldEnemySpawns(",
  "  group: WorldEnemyGroup",
  "): readonly WorldEnemySpawn[] {",
  "  return WORLD_ENEMY_SPAWNS.filter(",
  "    spawn =>",
  "      spawn.group === group",
  "  );",
  "}",
  ""
);

const output =
  lines.join("\n");

if (checkOnly) {
  if (!fs.existsSync(outputPath)) {
    throw new Error(
      `Generated runtime missing: ${outputPath}`
    );
  }

  const current =
    fs.readFileSync(outputPath, "utf8");

  if (current !== output) {
    throw new Error(
      "WorldEnemies.ts is stale."
    );
  }

  console.log(
    "LDtk enemy runtime synchronized: " +
    `${spawns.length} enemy spawns.`
  );

  process.exit(0);
}

fs.mkdirSync(
  path.dirname(outputPath),
  {
    recursive: true
  }
);

fs.writeFileSync(
  outputPath,
  output,
  "utf8"
);

console.log(
  "Generated src/world/WorldEnemies.ts: " +
  `${spawns.length} enemy spawns.`
);
