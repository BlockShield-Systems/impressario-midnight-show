import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();

const sourcePath = path.join(
  root,
  "assets/levels/impressario-world.ldtk"
);

const outputPath = path.join(
  root,
  "src/world/WorldGameplay.ts"
);

const checkOnly =
  process.argv.includes("--check");

const project = JSON.parse(
  fs.readFileSync(sourcePath, "utf8")
);

const level = project.levels?.find(
  value =>
    value.identifier ===
    "ImpressarioWorld"
);

const layer =
  level?.layerInstances?.find(
    value =>
      value.__identifier ===
      "Entities"
  );

if (!level || !layer) {
  throw new Error(
    "ImpressarioWorld Entities layer is missing."
  );
}

const fieldsOf = entity =>
  new Map(
    entity.fieldInstances.map(
      field => [
        field.__identifier,
        field.__value
      ]
    )
  );

const checkpoints =
  layer.entityInstances
    .filter(
      entity =>
        entity.__identifier ===
        "Checkpoint"
    )
    .map(entity => {
      const fields =
        fieldsOf(entity);

      return {
        id: String(
          fields.get("Identifier") ?? ""
        ),
        displayName: String(
          fields.get("DisplayName") ?? ""
        ),
        triggerX: Number(
          fields.get("TriggerX")
        ),
        x: Number(entity.px?.[0]),
        y: Number(entity.px?.[1])
      };
    })
    .sort(
      (left, right) =>
        left.triggerX -
        right.triggerX
    );

const gates =
  layer.entityInstances
    .filter(
      entity =>
        entity.__identifier ===
        "GameplayGate"
    )
    .map(entity => {
      const fields =
        fieldsOf(entity);

      return {
        id: String(
          fields.get("Identifier") ?? ""
        ),
        x: Number(entity.px?.[0]),
        y: Number(entity.px?.[1]),
        width: Number(entity.width),
        height: Number(entity.height)
      };
    })
    .sort(
      (left, right) =>
        left.x - right.x ||
        left.y - right.y
    );

if (checkpoints.length !== 11) {
  throw new Error(
    `Expected 11 checkpoints, got ${
      checkpoints.length
    }.`
  );
}

if (gates.length !== 9) {
  throw new Error(
    `Expected 9 gameplay gates, got ${
      gates.length
    }.`
  );
}

const assertUnique = (
  values,
  label
) => {
  const ids =
    values.map(value => value.id);

  if (
    ids.some(id => !id) ||
    new Set(ids).size !== ids.length
  ) {
    throw new Error(
      `${label} identifiers are invalid.`
    );
  }
};

assertUnique(
  checkpoints,
  "Checkpoint"
);

assertUnique(
  gates,
  "Gameplay gate"
);

for (const checkpoint of checkpoints) {
  if (
    !checkpoint.displayName ||
    !Number.isInteger(
      checkpoint.triggerX
    ) ||
    !Number.isInteger(checkpoint.x) ||
    !Number.isInteger(checkpoint.y) ||
    checkpoint.x < 0 ||
    checkpoint.x > level.pxWid ||
    checkpoint.y < 0 ||
    checkpoint.y > level.pxHei ||
    checkpoint.triggerX < 0 ||
    checkpoint.triggerX >
      level.pxWid
  ) {
    throw new Error(
      `Checkpoint ${
        checkpoint.id
      } is invalid.`
    );
  }
}

for (const gate of gates) {
  if (
    !Number.isInteger(gate.x) ||
    !Number.isInteger(gate.y) ||
    !Number.isInteger(gate.width) ||
    !Number.isInteger(gate.height) ||
    gate.width <= 0 ||
    gate.height <= 0 ||
    gate.x < 0 ||
    gate.y < 0 ||
    gate.x + gate.width >
      level.pxWid ||
    gate.y + gate.height >
      level.pxHei
  ) {
    throw new Error(
      `Gameplay gate ${
        gate.id
      } is invalid.`
    );
  }
}

const quote = value =>
  JSON.stringify(value);

const checkpointIds =
  checkpoints
    .map(
      value =>
        `  | ${quote(value.id)}`
    )
    .join("\n");

const gateIds =
  gates
    .map(
      value =>
        `  | ${quote(value.id)}`
    )
    .join("\n");

const lines = [
  "/* Generated by scripts/sync-ldtk-gameplay.mjs. */",
  "/* Edit assets/levels/impressario-world.ldtk, not this file. */",
  "",
  "export type WorldCheckpointId =",
  `${checkpointIds};`,
  "",
  "export type WorldGateId =",
  `${gateIds};`,
  "",
  "export interface WorldCheckpoint {",
  "  readonly id: WorldCheckpointId;",
  "  readonly displayName: string;",
  "  readonly triggerX: number;",
  "  readonly x: number;",
  "  readonly y: number;",
  "}",
  "",
  "export interface WorldGate {",
  "  readonly id: WorldGateId;",
  "  readonly x: number;",
  "  readonly y: number;",
  "  readonly width: number;",
  "  readonly height: number;",
  "}",
  "",
  "export const WORLD_CHECKPOINTS: readonly WorldCheckpoint[] = ["
];

for (const value of checkpoints) {
  lines.push(
    "  { " +
      `id: ${quote(value.id)}, ` +
      `displayName: ${
        quote(value.displayName)
      }, ` +
      `triggerX: ${
        value.triggerX
      }, ` +
      `x: ${value.x}, ` +
      `y: ${value.y} ` +
      "},"
  );
}

lines.push(
  "] as const;",
  "",
  "export const WORLD_GATES: readonly WorldGate[] = ["
);

for (const value of gates) {
  lines.push(
    "  { " +
      `id: ${quote(value.id)}, ` +
      `x: ${value.x}, ` +
      `y: ${value.y}, ` +
      `width: ${value.width}, ` +
      `height: ${value.height} ` +
      "},"
  );
}

lines.push(
  "] as const;",
  "",
  "export function getWorldCheckpoint(",
  "  id: WorldCheckpointId",
  "): WorldCheckpoint {",
  "  const value =",
  "    WORLD_CHECKPOINTS.find(",
  "      candidate =>",
  "        candidate.id === id",
  "    );",
  "",
  "  if (!value) {",
  "    throw new Error(",
  "      `Unknown checkpoint: ${id}`",
  "    );",
  "  }",
  "",
  "  return value;",
  "}",
  "",
  "export function getWorldGate(",
  "  id: WorldGateId",
  "): WorldGate {",
  "  const value =",
  "    WORLD_GATES.find(",
  "      candidate =>",
  "        candidate.id === id",
  "    );",
  "",
  "  if (!value) {",
  "    throw new Error(",
  "      `Unknown gameplay gate: ${id}`",
  "    );",
  "  }",
  "",
  "  return value;",
  "}",
  ""
);

const generated =
  lines.join("\n");

if (checkOnly) {
  if (
    !fs.existsSync(outputPath) ||
    fs.readFileSync(
      outputPath,
      "utf8"
    ) !== generated
  ) {
    throw new Error(
      "WorldGameplay.ts is stale. " +
      "Run npm run levels:sync."
    );
  }

  console.log(
    "LDtk gameplay runtime valid: " +
    `${checkpoints.length} checkpoints, ` +
    `${gates.length} gates.`
  );
} else {
  fs.writeFileSync(
    outputPath,
    generated,
    "utf8"
  );

  console.log(
    `Generated ${
      path.relative(
        root,
        outputPath
      )
    }: ` +
    `${checkpoints.length} checkpoints, ` +
    `${gates.length} gates.`
  );
}
