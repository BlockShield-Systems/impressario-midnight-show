import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();

const sourcePath = path.join(
  root,
  "assets/levels/impressario-world.ldtk"
);

const outputPath = path.join(
  root,
  "src/world/WorldHazards.ts"
);

const checkOnly =
  process.argv.includes("--check");

const project = JSON.parse(
  fs.readFileSync(sourcePath, "utf8")
);

if (project.jsonVersion !== "1.5.3") {
  throw new Error(
    `Unexpected LDtk version ${project.jsonVersion}.`
  );
}

const level = project.levels?.find(
  value =>
    value.identifier ===
    "ImpressarioWorld"
);

const layer = level?.layerInstances?.find(
  value =>
    value.__identifier === "Entities"
);

if (!level || !layer) {
  throw new Error(
    "ImpressarioWorld Entities layer is missing."
  );
}

const fieldValue = (
  entity,
  identifier
) => {
  const field =
    entity.fieldInstances?.find(
      value =>
        value.__identifier === identifier
    );

  if (!field) {
    throw new Error(
      `${entity.__identifier} missing ${identifier}.`
    );
  }

  return field.__value;
};

const hazards =
  layer.entityInstances
    .filter(
      entity =>
        entity.__identifier ===
        "HazardAnchor"
    )
    .map(entity => ({
      id: String(
        fieldValue(entity, "Identifier")
      ),
      group: String(
        fieldValue(entity, "Group")
      ),
      kind: String(
        fieldValue(entity, "Kind")
      ),
      x: Number(entity.px?.[0]),
      y: Number(entity.px?.[1]),
      width: Number(entity.width),
      height: Number(entity.height),
      travelX: Number(
        fieldValue(entity, "TravelX")
      ),
      travelY: Number(
        fieldValue(entity, "TravelY")
      ),
      speed: Number(
        fieldValue(entity, "Speed")
      ),
      phase: Number(
        fieldValue(entity, "Phase")
      )
    }))
    .sort(
      (a, b) =>
        a.x - b.x ||
        a.y - b.y ||
        a.id.localeCompare(b.id)
    );

const supports =
  layer.entityInstances
    .filter(
      entity =>
        entity.__identifier ===
        "SupportPickup"
    )
    .map(entity => ({
      id: String(
        fieldValue(entity, "Identifier")
      ),
      group: String(
        fieldValue(entity, "Group")
      ),
      x: Number(entity.px?.[0]),
      y: Number(entity.px?.[1])
    }))
    .sort(
      (a, b) =>
        a.x - b.x ||
        a.y - b.y ||
        a.id.localeCompare(b.id)
    );

const expected = {
  "Gallery:Pendulum": 2,
  "Gallery:Spike": 2,
  "CardSanctum:Blade": 4,
  "CardSanctum:Spike": 4,
  "RoyalBox:Spike": 5,
  "RoyalBox:Blade": 4,
  "RoyalBox:Laser": 4,
  "MirrorCore:Spike": 4
};

if (hazards.length !== 29) {
  throw new Error(
    `Expected 29 hazards, got ${hazards.length}.`
  );
}

if (supports.length !== 8) {
  throw new Error(
    `Expected 8 supports, got ${supports.length}.`
  );
}

const ids = new Set();

for (const item of [
  ...hazards,
  ...supports
]) {
  if (!item.id || ids.has(item.id)) {
    throw new Error(
      `Invalid or duplicate ID: ${item.id}`
    );
  }

  ids.add(item.id);

  if (
    !Number.isFinite(item.x) ||
    !Number.isFinite(item.y) ||
    item.x < 0 ||
    item.x > level.pxWid ||
    item.y < 0 ||
    item.y > level.pxHei
  ) {
    throw new Error(
      `${item.id} has invalid position.`
    );
  }
}

for (const hazard of hazards) {
  for (
    const [name, value] of
    Object.entries(hazard)
  ) {
    if (
      typeof value === "number" &&
      !Number.isFinite(value)
    ) {
      throw new Error(
        `${hazard.id} has invalid ${name}.`
      );
    }
  }

  if (
    hazard.width <= 0 ||
    hazard.height <= 0
  ) {
    throw new Error(
      `${hazard.id} has invalid dimensions.`
    );
  }
}

for (
  const [key, expectedCount] of
  Object.entries(expected)
) {
  const [group, kind] = key.split(":");

  const actual = hazards.filter(
    value =>
      value.group === group &&
      value.kind === kind
  ).length;

  if (actual !== expectedCount) {
    throw new Error(
      `Expected ${expectedCount} ${key}, got ${actual}.`
    );
  }
}

for (
  const [group, expectedCount] of [
    ["RoyalBox", 4],
    ["MirrorCore", 4]
  ]
) {
  const actual = supports.filter(
    value => value.group === group
  ).length;

  if (actual !== expectedCount) {
    throw new Error(
      `Expected ${expectedCount} ${group} supports, got ${actual}.`
    );
  }
}

const lines = [
  "/* Generated by scripts/sync-ldtk-hazards.mjs. */",
  "/* Edit assets/levels/impressario-world.ldtk, not this file. */",
  "",
  "export type WorldHazardGroup =",
  '  | "Gallery"',
  '  | "CardSanctum"',
  '  | "RoyalBox"',
  '  | "MirrorCore";',
  "",
  "export type WorldHazardKind =",
  '  | "Pendulum"',
  '  | "Spike"',
  '  | "Blade"',
  '  | "Laser";',
  "",
  "export interface WorldHazard {",
  "  readonly id: string;",
  "  readonly group: WorldHazardGroup;",
  "  readonly kind: WorldHazardKind;",
  "  readonly x: number;",
  "  readonly y: number;",
  "  readonly width: number;",
  "  readonly height: number;",
  "  readonly travelX: number;",
  "  readonly travelY: number;",
  "  readonly speed: number;",
  "  readonly phase: number;",
  "}",
  "",
  "export interface WorldSupportPickup {",
  "  readonly id: string;",
  "  readonly group: WorldHazardGroup;",
  "  readonly x: number;",
  "  readonly y: number;",
  "}",
  "",
  "export const WORLD_HAZARDS = ["
];

for (const value of hazards) {
  lines.push(
    "  {",
    `    id: ${JSON.stringify(value.id)},`,
    `    group: ${JSON.stringify(value.group)},`,
    `    kind: ${JSON.stringify(value.kind)},`,
    `    x: ${value.x},`,
    `    y: ${value.y},`,
    `    width: ${value.width},`,
    `    height: ${value.height},`,
    `    travelX: ${value.travelX},`,
    `    travelY: ${value.travelY},`,
    `    speed: ${value.speed},`,
    `    phase: ${value.phase}`,
    "  },"
  );
}

lines.push(
  "] as const satisfies readonly WorldHazard[];",
  "",
  "export const WORLD_SUPPORT_PICKUPS = ["
);

for (const value of supports) {
  lines.push(
    "  {",
    `    id: ${JSON.stringify(value.id)},`,
    `    group: ${JSON.stringify(value.group)},`,
    `    x: ${value.x},`,
    `    y: ${value.y}`,
    "  },"
  );
}

lines.push(
  "] as const satisfies readonly WorldSupportPickup[];",
  "",
  "export function getWorldHazards(",
  "  group: WorldHazardGroup,",
  "  kind: WorldHazardKind",
  "): readonly WorldHazard[] {",
  "  return WORLD_HAZARDS.filter(",
  "    value =>",
  "      value.group === group &&",
  "      value.kind === kind",
  "  );",
  "}",
  "",
  "export function getWorldSupportPickups(",
  "  group: WorldHazardGroup",
  "): readonly WorldSupportPickup[] {",
  "  return WORLD_SUPPORT_PICKUPS.filter(",
  "    value => value.group === group",
  "  );",
  "}",
  ""
);

const output = lines.join("\n");

if (checkOnly) {
  if (
    !fs.existsSync(outputPath) ||
    fs.readFileSync(
      outputPath,
      "utf8"
    ) !== output
  ) {
    throw new Error(
      "WorldHazards.ts is stale."
    );
  }

  console.log(
    "LDtk hazard runtime synchronized: " +
    "29 hazards, 8 supports."
  );

  process.exit(0);
}

fs.writeFileSync(
  outputPath,
  output,
  "utf8"
);

console.log(
  "Generated src/world/WorldHazards.ts: " +
  "29 hazards, 8 supports."
);
